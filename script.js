function currentLanguage() {
  return document.getElementById("languageSelect")?.value || "fr";
}

function setText(id, value) {
  const element = document.getElementById(id);
  if (element) {
    element.textContent = value;
  }
}

function toggleDarkMode() {
  document.body.classList.toggle("dark-mode");
  drawProgressChart(75);
}

function changeLanguage() {
  const t = translations[currentLanguage()] || translations.fr;

  document.documentElement.lang = t.htmlLang;
  document.title = t.pageTitle;

  Object.entries(textBindings).forEach(([id, key]) => {
    setText(id, t[key]);
  });

  const adviceList = document.getElementById("advice-list");
  if (adviceList) {
    adviceList.innerHTML = "";
    t.adviceList.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      adviceList.appendChild(li);
    });
  }

  drawProgressChart(75);
}

function showAnotherAdvice() {
  const advices = allAdvices[currentLanguage()] || allAdvices.fr;
  const randomAdvice = advices[Math.floor(Math.random() * advices.length)];
  const adviceList = document.getElementById("advice-list");

  if (adviceList) {
    adviceList.innerHTML = "";
    const li = document.createElement("li");
    li.textContent = randomAdvice;
    adviceList.appendChild(li);
  }
}

function showAnotherQuote() {
  const quotes = motivationalQuotes[currentLanguage()] || motivationalQuotes.fr;
  const randomQuote = quotes[Math.floor(Math.random() * quotes.length)];
  setText("motivation-quote", randomQuote);
}

function drawProgressChart(percent) {
  const canvas = document.getElementById("progress-chart");
  if (!canvas) return;

  const ctx = canvas.getContext("2d");
  const size = canvas.width;
  const center = size / 2;
  const radius = center - 18;
  const start = -Math.PI / 2;
  const end = start + (Math.PI * 2 * percent) / 100;

  ctx.clearRect(0, 0, size, size);
  ctx.lineWidth = 16;
  ctx.lineCap = "round";

  ctx.beginPath();
  ctx.strokeStyle = "rgba(219, 39, 119, 0.16)";
  ctx.arc(center, center, radius, 0, Math.PI * 2);
  ctx.stroke();

  const gradient = ctx.createLinearGradient(30, 30, size - 30, size - 30);
  gradient.addColorStop(0, "#F472B6");
  gradient.addColorStop(1, "#DB2777");

  ctx.beginPath();
  ctx.strokeStyle = gradient;
  ctx.arc(center, center, radius, start, end);
  ctx.stroke();

  ctx.fillStyle = getComputedStyle(document.body).getPropertyValue("--text").trim() || "#0F172A";
  ctx.font = "700 34px Inter, Arial, sans-serif";
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  ctx.fillText(`${percent}%`, center, center);
}

document.addEventListener("DOMContentLoaded", () => {
  document.getElementById("languageSelect")?.addEventListener("change", changeLanguage);
  changeLanguage();
});
